import { CreateBucketCommand, PutObjectCommand } from '@aws-sdk/client-s3';
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import pg from 'pg';
import { buildApp } from '../../src/app.js';
import { createSessionToken, hashPassword, SESSION_COOKIE_NAME } from '../../src/auth.js';
import { createPool } from '../../src/db.js';
import { createS3Client } from '../../src/s3.js';

const TEST_DATABASE_URL = 'postgresql://postgres:postgres@localhost:5433/dashboard_test';
const SESSION_SECRET = 'test-secret';
const BUCKET = 'dashboard-test-bucket';

function authCookie() {
  return `${SESSION_COOKIE_NAME}=${createSessionToken(SESSION_SECRET)}`;
}

describe('GET /api/sessions/:dumpId', () => {
  let pool: pg.Pool;
  let app: ReturnType<typeof buildApp>;

  beforeAll(async () => {
    pool = createPool(TEST_DATABASE_URL);
    const s3 = { client: createS3Client({
      endpoint: 'http://localhost:9100', region: 'us-east-1',
      accessKeyId: 'minioadmin', secretAccessKey: 'minioadmin', bucket: BUCKET, forcePathStyle: true
    }), bucket: BUCKET };
    try {
      await s3.client.send(new CreateBucketCommand({ Bucket: BUCKET }));
    } catch (err) {
      const name = err instanceof Error ? err.name : '';
      if (name !== 'BucketAlreadyOwnedByYou' && name !== 'BucketAlreadyExists') throw err;
    }
    app = buildApp({ pool, config: { passwordHash: hashPassword('x'), sessionSecret: SESSION_SECRET }, s3 });
  });

  afterAll(async () => {
    await pool.end();
  });

  beforeEach(async () => {
    await pool.query('drop table if exists dashboard_observations, dashboard_analysis, "rtcstats-server", features_metadata, features_client, features_connection, features_track cascade');
    await pool.query(`
      create table "rtcstats-server" (
        id bigint generated by default as identity primary key,
        session_start timestamptz, session_end timestamptz, blob_url text,
        rtcstats_user text, rtcstats_conference text, host_identifier text,
        features_processing_start timestamptz, features_processing_stop timestamptz
      );
      create table features_metadata (
        id bigint generated by default as identity primary key,
        dump_id bigint references "rtcstats-server"(id),
        start_time timestamptz, useragent text, number_peerconnections smallint
      );
      create table features_client (
        id bigint generated by default as identity primary key,
        dump_id bigint references features_metadata(id) on delete cascade,
        hardware_concurrency smallint, device_memory smallint,
        called_get_user_media boolean default false,
        get_user_media_success_count integer default 0,
        get_user_media_error_count integer default 0,
        get_user_media_error text,
        reload_count integer, cpu_performance smallint, operating_system text,
        audio_ended boolean default false, audio_short_duration boolean default false,
        video_ended boolean default false, video_short_duration boolean default false
      );
      create table features_connection (
        id bigint generated by default as identity primary key,
        dump_id bigint references features_metadata(id) on delete cascade,
        connection_identifier text, closed boolean,
        ice_connected boolean default false, ice_connection_time integer,
        ice_restart boolean default false,
        add_ice_candidate_failure text, set_local_description_failure text, set_remote_description_failure text,
        connected boolean, dtls_version text, dtls_role text, added_null_candidate boolean,
        first_candidate_pair_local_type text, first_candidate_pair_remote_type text,
        average_stun_round_trip_time float,
        ice_restart_followed_by_set_remote_description boolean default false,
        signaling_delay integer, set_remote_description_delay integer, set_local_description_delay integer,
        set_local_description_role text, set_remote_description_role text,
        clock_skew integer, gathering_time_turn_udp integer, gathering_time_turn_tcp integer, gathering_time_turn_tls integer
      );
      create table features_track (
        id bigint generated by default as identity primary key,
        connection_id bigint references features_connection(id) on delete cascade,
        track_identifier text, kind text, direction text,
        frame_count integer, quality_limitation_resolution_changes integer,
        bandwidth_quality_limitation_percentage float, cpu_quality_limitation_percentage float, other_quality_limitation_percentage float,
        average_encode_time float, average_decode_time float,
        freeze_count integer, total_freezes_duration float, qp_sum integer,
        encoder_implementation text, power_efficient_encoder boolean,
        decoder_implementation text, power_efficient_decoder boolean, has_null_video_decoder boolean,
        concealed_samples integer, total_samples_received integer, concealment_percentage float,
        jitter_buffer_flushes integer, has_periodic_jitter_buffer_flushes boolean,
        inserted_samples_for_deceleration integer, removed_samples_for_acceleration integer,
        deceleration_percentage float, acceleration_percentage float, time_to_first_frame integer
      );
      create table dashboard_analysis (
        id bigint generated by default as identity primary key,
        dump_id bigint not null unique references "rtcstats-server"(id) on delete cascade,
        rules_version text not null, status text not null default 'ok',
        error text, session_start timestamptz, duration integer,
        rtcstats_user text, rtcstats_conference text,
        experience_score real, audio_score real, video_score real, connectivity_score real,
        observation_types text[] not null default '{}', worst_severity text,
        observations_count jsonb not null default '{}',
        audio_mos real, video_mos real
      );
      create table dashboard_observations (
        id bigint generated by default as identity primary key,
        analysis_id bigint not null references dashboard_analysis(id) on delete cascade,
        pid text, type text not null, severity text not null, category text not null,
        first_seen_at double precision, observation jsonb not null
      );
    `);
  });

  it('returns 404 for a dump with no analysis', async () => {
    const response = await app.inject({ method: 'GET', url: '/api/sessions/999999', headers: { cookie: authCookie() } });
    expect(response.statusCode).toBe(404);
  });

  it('composes analysis, observations, features, and dump availability for a present dump', async () => {
    const s3 = { client: createS3Client({
      endpoint: 'http://localhost:9100', region: 'us-east-1',
      accessKeyId: 'minioadmin', secretAccessKey: 'minioadmin', bucket: BUCKET, forcePathStyle: true
    }), bucket: BUCKET };

    const dump = await pool.query(
      `insert into "rtcstats-server" (rtcstats_user, session_start, session_end, blob_url, features_processing_stop)
       values ('alice', now() - interval '5 minutes', now(), $1, now()) returning id`,
      [`s3://${BUCKET}/dumps/present.json.gz`]
    );
    const dumpId = dump.rows[0].id;

    await s3.client.send(new PutObjectCommand({ Bucket: BUCKET, Key: 'dumps/present.json.gz', Body: Buffer.from('x'.repeat(1234)) }));

    const metadata = await pool.query(`insert into features_metadata (dump_id, number_peerconnections) values ($1, 1) returning id`, [dumpId]);
    await pool.query(`insert into features_client (dump_id, hardware_concurrency) values ($1, 8)`, [metadata.rows[0].id]);

    const analysis = await pool.query(
      `insert into dashboard_analysis (dump_id, rules_version, status, session_start, duration, rtcstats_user, experience_score, worst_severity, observation_types, observations_count, audio_mos, video_mos)
       values ($1, '1.0.0', 'ok', now(), 300, 'alice', 65, 'critical', '{video.freezes}', '{"critical":1}', 4.25, 3.5) returning id`,
      [dumpId]
    );
    await pool.query(
      `insert into dashboard_observations (analysis_id, pid, type, severity, category, first_seen_at, observation)
       values ($1, 'PC_0', 'video.freezes', 'critical', 'video', 12.5, '{"count":3}')`,
      [analysis.rows[0].id]
    );

    const response = await app.inject({ method: 'GET', url: `/api/sessions/${dumpId}`, headers: { cookie: authCookie() } });
    if (response.statusCode !== 200) {
      console.error('ERROR response:', response.body);
    }
    expect(response.statusCode).toBe(200);
    const body = response.json();
    expect(body.analysis.experienceScore).toBe(65);
    expect(body.analysis.audioMos).toBeCloseTo(4.25, 5);
    expect(body.analysis.videoMos).toBeCloseTo(3.5, 5);
    expect(body.observations).toHaveLength(1);
    expect(body.observations[0].type).toBe('video.freezes');
    expect(body.features.client?.hardwareConcurrency).toBe(8);
    expect(body.dump).toEqual({ sizeBytes: 1234, status: 'available' });
  });

  it('reports dump.status as missing when the object is gone from storage', async () => {
    const dump = await pool.query(
      `insert into "rtcstats-server" (rtcstats_user, session_start, session_end, blob_url, features_processing_stop)
       values ('bob', now() - interval '5 minutes', now(), $1, now()) returning id`,
      [`s3://${BUCKET}/dumps/gone.json.gz`]
    );
    const dumpId = dump.rows[0].id;
    await pool.query(`insert into features_metadata (dump_id, number_peerconnections) values ($1, 1)`, [dumpId]);
    await pool.query(
      `insert into dashboard_analysis (dump_id, rules_version, status) values ($1, '1.0.0', 'ok')`,
      [dumpId]
    );

    const response = await app.inject({ method: 'GET', url: `/api/sessions/${dumpId}`, headers: { cookie: authCookie() } });
    expect(response.json().dump).toEqual({ sizeBytes: null, status: 'missing' });
  });
});
